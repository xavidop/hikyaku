// SchemaBaseURL is where the schema is published (design §15 Q3).
const SchemaBaseURL = "https://xavidop.github.io/hikyaku/schema/"

func newReflector() *jsonschema.Reflector {
	return &jsonschema.Reflector{
		ExpandedStruct:             true,
		RequiredFromJSONSchemaTags: true,
		FieldNameTag:               "yaml",
	}
}

// Schema is the JSON Schema of hikyaku.yaml (schema/hikyaku.schema.json).
func Schema() *jsonschema.Schema {
	s := newReflector().Reflect(&Spec{})
	s.ID = jsonschema.ID(SchemaBaseURL + "hikyaku.schema.json")
	s.Title = "hikyaku.yaml"
	s.Description = "A hikyaku relay: sources, destinations, routes and their retry and fallback policies. See https://xavidop.github.io/hikyaku/docs/spec-reference/."
	return s
}

// SchemaJSON renders a schema as indented JSON with a trailing newline, the
// committed form.
func SchemaJSON(s *jsonschema.Schema) ([]byte, error) {
	b, err := json.MarshalIndent(s, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

// ReferenceMarkdown renders the spec reference page of the docs site from
// the schema: one table per section, in the order a spec reads.
func ReferenceMarkdown() []byte {
	s := Schema()
	var b bytes.Buffer
	b.WriteString("---\nlayout: ../../layouts/DocsLayout.astro\ntitle: Spec reference (YAML)\n---\n\n")
	b.WriteString("<!-- Generated by `make schema`; edit the config types and their jsonschema tags, not this file. -->\n\n")
	b.WriteString("# Spec reference\n\n")
	b.WriteString("Generated from the Go structs by `make schema`; the JSON Schema is [`hikyaku.schema.json`](" + SchemaBaseURL + "hikyaku.schema.json).\n")
	b.WriteString("Point your editor at it with `# yaml-language-server: $schema=" + SchemaBaseURL + "hikyaku.schema.json`.\n\n")
	b.WriteString("Durations read like `500ms`, `30s`, `5m`, `1h`, `7d`; sizes like `512`, `8KiB`, `10MB`. `{{secrets.NAME}}` and `{{env.NAME}}` are replaced when the spec loads; `{{ .json.x }}` templates run per message.\n\n")
	writeTable(&b, "Top level (`hikyaku.yaml`)", s.Properties, s.Required)
	names := make([]string, 0, len(s.Definitions))
	for n := range s.Definitions {
		names = append(names, n)
	}
	order := []string{"Source", "Destination", "Member", "Endpoint", "Policy", "Retry", "CircuitBreaker", "RetryBudget", "Route", "RouterSpec", "Rule", "Candidate", "AIInput", "Cache", "History", "Window", "HistoryRecord", "Sticky", "AIBudget", "Transform", "HeaderOps", "Store", "DeadLetter"}
	sort.SliceStable(names, func(i, j int) bool {
		ii, jj := slices.Index(order, names[i]), slices.Index(order, names[j])
		if ii < 0 {
			ii = len(order)
		}
		if jj < 0 {
			jj = len(order)
		}
		if ii != jj {
			return ii < jj
		}
		return names[i] < names[j]
	})
	var scalars []string
	for _, n := range names {
		d := s.Definitions[n]
		if d.Properties == nil || d.Properties.Len() == 0 {
			scalars = append(scalars, n)
			continue
		}
		writeTable(&b, "`"+n+"`", d.Properties, d.Required)
	}
	// The tables link these types too (typeOf), so each needs an anchor.
	if len(scalars) > 0 {
		b.WriteString("## Scalar types\n\n")
		for _, n := range scalars {
			d := s.Definitions[n]
			desc := d.Description
			if desc == "" {
				desc = "A " + typeOf(d) + "."
			}
			fmt.Fprintf(&b, "### `%s`\n\n%s\n\n", n, strings.ReplaceAll(desc, "|", "\\|"))
		}
	}
	return b.Bytes()
}

func writeTable(b *bytes.Buffer, title string, props *orderedmap.OrderedMap[string, *jsonschema.Schema], required []string) {
	fmt.Fprintf(b, "## %s\n\n| Key | Type | Description |\n|---|---|---|\n", title)
	for pair := props.Oldest(); pair != nil; pair = pair.Next() {
		key, p := pair.Key, pair.Value
		req := ""
		if slices.Contains(required, key) {
			req = " **(required)**"
		}
		desc := strings.ReplaceAll(p.Description, "|", "\\|")
		if len(p.Enum) > 0 {
			vals := make([]string, len(p.Enum))
			for i, e := range p.Enum {
				vals[i] = fmt.Sprintf("`%v`", e)
			}
			desc += " One of " + strings.Join(vals, ", ") + "."
		}
		fmt.Fprintf(b, "| `%s`%s | %s | %s |\n", key, req, typeOf(p), strings.ReplaceAll(desc, "\n", " "))
	}
	b.WriteString("\n")
}

func typeOf(p *jsonschema.Schema) string {
	switch {
	case p.Ref != "":
		return "[" + strings.TrimPrefix(p.Ref, "#/$defs/") + "](#" + strings.ToLower(strings.TrimPrefix(p.Ref, "#/$defs/")) + ")"
	case p.Type == "array" && p.Items != nil:
		return typeOf(p.Items) + "[]"
	case p.Type == "object" && p.AdditionalProperties != nil:
		return "map of " + typeOf(p.AdditionalProperties)
	case len(p.OneOf) > 0:
		parts := make([]string, len(p.OneOf))
		for i, o := range p.OneOf {
			parts[i] = typeOf(o)
		}
		return strings.Join(parts, " or ")
	case p.Type != "":
		return p.Type
	}
	return "any"
}
